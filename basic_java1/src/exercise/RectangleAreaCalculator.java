package exercise;

public class RectangleAreaCalculator {

    public static void main(String[] args) {
        // 단, 상수를 사용해 보세요
        // 직접 코드의 흐름을 만들어보세요.

        //주석으로 작성 습관
        // 사각형에 가로 길이를 상수로 선언해보자.

        final int num1 = 3;  // num1 = 가로, 가로길이를 상수로 선언
        final int num2 = 5;  // num2 = 세로, 세로길이를 상수로 선언

        // 사각형 면적 = 가로 * 세로
        int area = num1 * num2;
        System.out.println("사각형 면적:" + area);



    } //end of main
} //end of class
